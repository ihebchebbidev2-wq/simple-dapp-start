function canonicalAppBaseUrl(): string {
  // OAuth redirect URIs must point to the public frontend (e.g. https://www.remquip.ca),
  // NOT the backend host. Prefer VITE_PUBLIC_APP_URL, then SITE_URL, then current origin.
  const envUrl = (typeof import.meta.env.VITE_PUBLIC_APP_URL === "string"
    ? import.meta.env.VITE_PUBLIC_APP_URL
    : "").trim().replace(/\/+$/, "");
  if (envUrl) return envUrl;
  if (SITE_URL) return SITE_URL.replace(/\/+$/, "");
  if (typeof window !== "undefined" && window.location?.origin) return window.location.origin;
  return "";
}

function oauthCallbackUrl(providerId: ProviderId): string {
  return `${canonicalAppBaseUrl()}/admin/integrations/oauth/${providerId}`;
}

