function CopyableUrl({ value }: { value: string }) {
  const [copied, setCopied] = useState(false);

  const copy = async () => {
    try {
      await navigator.clipboard.writeText(value);
      setCopied(true);
      showSuccessToast("URL copied to clipboard");
      setTimeout(() => setCopied(false), 1800);
    } catch {
      showErrorToast("Could not copy to clipboard");
    }
  };

  return (
    <div className="flex gap-2">
      <Input value={value} readOnly className="font-mono text-xs" onFocus={(e) => e.currentTarget.select()} />
      <Button type="button" size="icon" variant="outline" onClick={copy} aria-label="Copy URL">
        {copied ? <Check className="h-4 w-4 text-success" /> : <Copy className="h-4 w-4" />}
      </Button>
    </div>
  );
}

