function statusBadge(status: Status) {
  const map: Record<Status, { variant: any; icon: any; label: string }> = {
    connected:    { variant: "default",     icon: CheckCircle2,   label: "Connected" },
    disconnected: { variant: "secondary",   icon: XCircle,        label: "Disconnected" },
    pending:      { variant: "outline",     icon: Loader2,        label: "Pending" },
    error:        { variant: "destructive", icon: AlertTriangle,  label: "Error" },
  };
  const cfg = map[status] ?? map.disconnected;
  const Icon = cfg.icon;
  return (
    <Badge variant={cfg.variant} className="gap-1">
      <Icon className={`h-3 w-3 ${status === "pending" ? "animate-spin" : ""}`} />
      {cfg.label}
    </Badge>
  );
}

